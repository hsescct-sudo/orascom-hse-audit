#!/usr/bin/env python3
"""Writes audit/sw.js with the list of every file the app needs offline.
Run after changing files:  python3 audit/tools/build-sw.py"""
import hashlib, os, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
skip_dirs = {"tools"}
files, h = [], hashlib.sha256()
for p in sorted(root.rglob("*")):
    if p.is_dir() or p.name == "sw.js" or p.name.startswith(".") or any(part in skip_dirs for part in p.relative_to(root).parts):
        continue
    rel = p.relative_to(root).as_posix()
    files.append(rel)
    h.update(rel.encode()); h.update(p.read_bytes())
version = h.hexdigest()[:12]
lines = ",\n  ".join(f'"{f}"' for f in ["./"] + files)
(root / "sw.js").write_text(f"""// Offline support for OC HSE Audit. Generated by tools/build-sw.py, don't edit by hand.
// Every file of the app is saved on the device, so it opens and works with no internet.
const VERSION = "{version}";
const CACHE = "oc-hse-audit-" + VERSION;
const FILES = [
  {lines}
];
self.addEventListener("install", e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, {{ cache: "reload" }})))));
}});
self.addEventListener("activate", e => {{
  e.waitUntil((async () => {{
    for (const k of await caches.keys()) if (k.startsWith("oc-hse-audit-") && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  }})());
}});
self.addEventListener("message", e => {{ if (e.data === "update") self.skipWaiting(); }});
self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(new URL(self.registration.scope).pathname)) return;
  e.respondWith((async () => {{
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, {{ ignoreSearch: true }}) || (req.mode === "navigate" ? await cache.match("./") : null);
    if (hit) return hit;
    try {{
      const res = await fetch(req);
      if (res.ok) cache.put(req, res.clone());
      return res;
    }} catch (err) {{
      return new Response("Offline and this file isn't saved on the device yet.", {{ status: 503, headers: {{ "Content-Type": "text/plain" }} }});
    }}
  }})());
}});
""")
print(f"sw.js: {len(files)} files, version {version}")
